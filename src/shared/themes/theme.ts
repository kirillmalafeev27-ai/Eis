/**
 * Темы общей раскладки серии (0.7): стиль задаётся CSS-переменными и классом темы
 * на корне, а не прошит в разметке. «Бумага» — тема «Льдин».
 */
export interface Theme {
  name: string;
  /** Применить переменные темы к корню раскладки. */
  apply(root: HTMLElement): void;
  /** Оформить карточку (рваный край и т. п.) под её текущий размер. */
  decorateCard?(card: HTMLElement, seed: number): void;
}
